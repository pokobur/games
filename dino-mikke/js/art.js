    const SIL = { m: '#d3c6ad', b: '#d3c6ad', a: '#c6b89c', d: '#c6b89c', ink: '#a8977a', sil: true };

    function palette(id, opt) {
        const info = DM.data.DINOS[id];
        if (opt && opt.silhouette) return SIL;
        const c = Object.assign({}, info ? info.colors : {}, (opt && opt.colors) || {});
        c.m = c.m || '#cccccc';
        c.d = c.d || U.shade(c.m, -0.18);
        c.ink = INK;
        return c;
    }

    /** 200x160 ボックス内の SVG 断片（ラッパーg付き） */
    function body(id, opt) {
        const c = palette(id, opt);
        let inner;
        if (DRAW[id]) inner = DRAW[id](c);
        else if (ITEM_DRAW[id]) inner = ITEM_DRAW[id](c);
        else inner = '';
        if (c.sil && ITEM_DRAW[id]) {
            return `<g stroke="${c.ink}" stroke-width="3.2" stroke-linejoin="round" stroke-linecap="round" fill="${c.m}" opacity=".5">${inner}</g>`;
        }
        return `<g stroke="${c.ink}" stroke-width="3.2" stroke-linejoin="round" stroke-linecap="round">${inner}</g>`;
    }

    /** フィールド配置用 (中心 x,y、倍率 s) */
    function sprite(id, x, y, s, flip, opt) {
        const sx = flip ? -s : s;
        return `<g transform="translate(${U.f(x)} ${U.f(y)}) scale(${U.f(sx * 1000) / 1000} ${U.f(s * 1000) / 1000}) translate(-100 -80)">${body(id, opt)}</g>`;
    }

    /** 単体 SVG アイコン */
    function icon(id, opt) {
        const cls = (opt && opt.cls) || '';
        return `<svg class="${cls}" viewBox="-8 -6 216 172" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">${body(id, opt)}</svg>`;
    }

    /** 画像化用の完全 SVG 文字列 */
    function standalone(id, w, h, opt) {
        return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-8 -6 216 172" width="${w}" height="${h}">${body(id, opt)}</svg>`;
    }

