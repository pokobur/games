/**
 * プリセット名（日本語またはID）からパズルデータを生成
 */
export function getPresetPuzzle(query) {
  let matchedKey = 'cat';
  const q = (query || '').toLowerCase();

  for (const [key] of Object.entries(PRESET_DATA)) {
    if (q.includes(key)) {
      matchedKey = key;
      break;
    }
  }

  // 日本語マッチ
  if (q.includes('ねこ') || q.includes('ネコ') || q.includes('猫')) matchedKey = 'cat';
  else if (q.includes('りんご') || q.includes('リンゴ') || q.includes('林檎') || q.includes('アップル')) matchedKey = 'apple';
  else if (q.includes('ほし') || q.includes('ホシ') || q.includes('星') || q.includes('スター')) matchedKey = 'star';
  else if (q.includes('ロケット')) matchedKey = 'rocket';
  else if (q.includes('にじ') || q.includes('虹') || q.includes('レインボー')) matchedKey = 'rainbow';
  else if (q.includes('ドラゴン') || q.includes('りゅう') || q.includes('竜')) matchedKey = 'dragon';
  else if (q.includes('ケーキ')) matchedKey = 'cake';
  else if (q.includes('くるま') || q.includes('車') || q.includes('カー')) matchedKey = 'car';

  const data = PRESET_DATA[matchedKey] || PRESET_DATA.cat;
  const gridSize = 16;
  const grid = [];

  for (let y = 0; y < gridSize; y++) {
    const row = [];
    const line = data.map[y] || "0".repeat(gridSize);
    for (let x = 0; x < gridSize; x++) {
      const char = line[x] || '0';
      const colorIndex = parseInt(char, 10);
      row.push({
        colorIndex,
        solved: false
      });
    }
    grid.push(row);
  }

  return {
    palette: data.palette,
    grid,
    gridSize,
    key: matchedKey
  };
}
